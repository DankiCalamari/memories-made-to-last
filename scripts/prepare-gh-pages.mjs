import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();
const nextDir = path.join(projectRoot, '.next');
const outDir = path.join(projectRoot, 'out');

const rimraf = (p) => {
  if (fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true });
};
const mkdirp = (p) => fs.mkdirSync(p, { recursive: true });

const readStringLiteral = (filePath, key) => {
  const src = fs.readFileSync(filePath, 'utf8');
  const re = new RegExp(`${key}:\\s*['\"]([^'\"]+)['\"]`);
  const m = src.match(re);
  return m?.[1];
};

const nextConfigPath = path.join(projectRoot, 'next.config.ts');
const basePath =
  readStringLiteral(nextConfigPath, 'basePath') ||
  readStringLiteral(nextConfigPath, 'assetPrefix') ||
  '/memories-made-to-last';

const basePathStripped = basePath.replace(/^\//, '').replace(/\/$/, '');
const outBaseDir = path.join(outDir, basePathStripped);

rimraf(outDir);
mkdirp(outDir);

// 1) Copy public/ as-is
const publicDir = path.join(projectRoot, 'public');
if (fs.existsSync(publicDir)) {
  fs.cpSync(publicDir, outDir, { recursive: true });
}

// 2) Copy static assets generated by Next (CSS/JS/etc)
// For App Router with static prerendering, assets typically live in .next/static
const nextStaticDir = path.join(nextDir, 'static');
const destNextStaticDir = path.join(outBaseDir, '_next', 'static');
mkdirp(destNextStaticDir);
if (fs.existsSync(nextStaticDir)) {
  fs.cpSync(nextStaticDir, destNextStaticDir, { recursive: true });
}

const serverAppDir = path.join(nextDir, 'server', 'app');
if (!fs.existsSync(serverAppDir)) {
  console.error(`Missing folder: ${serverAppDir}`);
  process.exit(1);
}

// 3) Move/rename prerendered HTML into GitHub Pages-friendly structure
// Next trailingSlash=true means routes should be /<route>/index.html
const files = fs.readdirSync(serverAppDir);

for (const file of files) {
  const src = path.join(serverAppDir, file);

  const stat = fs.statSync(src);
  if (!stat.isFile()) continue;

  // Handle special text/xml outputs
  if (file === 'robots.txt') {
    mkdirp(outBaseDir);
    fs.copyFileSync(src, path.join(outBaseDir, 'robots.txt'));
    continue;
  }
  if (file === 'sitemap.xml') {
    mkdirp(outBaseDir);
    fs.copyFileSync(src, path.join(outBaseDir, 'sitemap.xml'));
    continue;
  }

  if (!file.endsWith('.html')) continue;

  if (file === 'index.html') {
    // Home page
    mkdirp(outBaseDir);
    fs.copyFileSync(src, path.join(outBaseDir, 'index.html'));
    continue;
  }

  // about.html -> /about/index.html
  const route = file.replace(/\.html$/, '');
  const destDir = path.join(outBaseDir, route);
  mkdirp(destDir);
  fs.copyFileSync(src, path.join(destDir, 'index.html'));
}

// 4) Rewrite any asset paths in exported HTML so they point under basePath
// Goal: remove double-prefix like /<base>/<base>/_next/... and ensure
//      all Next assets load from /<base>/_next/... on GitHub Pages.
const htmlFiles = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (entry.isFile() && p.endsWith('.html')) htmlFiles.push(p);
  }
};
if (fs.existsSync(outBaseDir)) walk(outBaseDir);

const nextWithBase = `/${basePathStripped}/_next/`;
const doubledNextWithBase = `/${basePathStripped}/${basePathStripped}/_next/`;
const placeholder = `__NEXT_WITH_BASEPATH_PLACEHOLDER_${Date.now()}__`;

for (const htmlPath of htmlFiles) {
  const original = fs.readFileSync(htmlPath, 'utf8');
  if (!original.includes('/_next/') && !original.includes('_next/')) continue;

  let updated = original;

  // 1) Collapse any already-doubled prefixes first.
  if (updated.includes(doubledNextWithBase)) {
    updated = updated.split(doubledNextWithBase).join(nextWithBase);
  }

  // 2) Protect already-correct URLs so the next step doesn't double them.
  updated = updated.split(nextWithBase).join(placeholder);

  // 3) Rewrite absolute Next URLs.
  //    This fixes href/src like href="/_next/..." or src="/_next/..."
  updated = updated.split('/_next/').join(nextWithBase);

  // 4) Rewrite relative _next/... forms (no leading slash).
  //    e.g. src="_next/static/..."
  updated = updated.replace(/(["'\s=\(])_next\//g, `$1${basePathStripped}/_next/`);

  // 5) Restore protected correct URLs.
  updated = updated.split(placeholder).join(nextWithBase);

  if (updated !== original) fs.writeFileSync(htmlPath, updated);
}

// 5) Root index redirect
const rootIndex = path.join(outDir, 'index.html');
const rootHtml = `<!doctype html>\n<html>\n  <head>\n    <meta http-equiv="refresh" content="0; url=${basePath}/" />\n    <link rel="canonical" href="${basePath}/" />\n  </head>\n  <body>\n    Redirecting to <a href="${basePath}/">${basePath}/</a>\n  </body>\n</html>\n`;
fs.writeFileSync(rootIndex, rootHtml);

console.log(`Prepared GitHub Pages export in: ${outDir}`);
